// Builds js/mapdata.js: a projected Europe (land, coast, borders) and city positions, from
// Natural Earth via world-atlas (public domain). Run once after changing cities or projection:
//   node tools/build-map.js
import fs from 'node:fs';
import { geoConicConformal, geoPath } from 'd3-geo';
import { feature, mesh } from 'topojson-client';

const W = 1000, H = 640;
const CITIES = {
  London: [-0.13, 51.51], Paris: [2.35, 48.86], Lisbon: [-9.14, 38.72], Bern: [7.45, 46.95],
  Berlin: [13.40, 52.52], Prague: [14.42, 50.08], Vienna: [16.37, 48.21], Budapest: [19.04, 47.50],
  Helsinki: [24.94, 60.17], Athens: [23.73, 37.98], Istanbul: [28.98, 41.01], Moscow: [37.62, 55.75],
};

const world = JSON.parse(fs.readFileSync(new URL('../node_modules/world-atlas/countries-50m.json', import.meta.url)));
const countries = feature(world, world.objects.countries);
const land = feature(world, world.objects.land);
const borders = mesh(world, world.objects.countries, (a, b) => a !== b);

const projection = geoConicConformal()
  .parallels([40, 60]).rotate([-14, 0]).center([0, 50.5])
  .scale(1180).translate([W / 2 - 10, H / 2 + 10])
  .clipExtent([[0, 0], [W, H]]);
const path = geoPath(projection).digits(1);

const cityXY = Object.fromEntries(Object.entries(CITIES).map(([k, ll]) => [k, projection(ll).map((v) => Math.round(v))]));
for (const [k, [x, y]] of Object.entries(cityXY)) if (x < 20 || y < 20 || x > W - 20 || y > H - 20) console.warn('city near edge:', k, x, y);

const out = `// Generated by tools/build-map.js from Natural Earth (public domain) via world-atlas. Do not edit.
export const MAP = ${JSON.stringify({ width: W, height: H, land: path(land), borders: path(borders), cityXY })};
`;
fs.writeFileSync(new URL('../js/mapdata.js', import.meta.url), out);
console.log('wrote js/mapdata.js', (out.length / 1024).toFixed(0) + 'KB', cityXY);
void countries;
